async fn repository_digest(
    transport: &HttpAcquisition,
    scope: &mut WorkScope,
    url: &str,
    transfer: TransferLimits,
) -> Result<(ExpectedDigest, ContentId)> {
    let mut assertion = None;
    for algorithm in ["sha256", "sha1", "md5"] {
        let document = match library::metadata_document(
            transport,
            scope,
            format!("{}.{}", url, algorithm),
            4096,
            transfer,
        )
        .await
        {
            Ok(document) => document,
            Err(error)
                if error
                    .downcast_ref::<TransferError>()
                    .is_some_and(|error| matches!(error, TransferError::NotFound)) =>
            {
                continue;
            }
            Err(error) => return Err(error),
        };
        let id = document.lease().id();
        let worker = scope.spawn_blocking(
            metadata_work(),
            ResourceRequest::default(),
            move |_| -> Result<_> {
                let mut text = String::new();
                document.lease().open().read_to_string(&mut text)?;
                let digest = ExpectedDigest::parse(
                    algorithm,
                    text.split_whitespace()
                        .next()
                        .context("Empty installer checksum")?,
                )?;
                Ok((digest, id))
            },
        )?;
        assertion = Some(
            scope
                .accept(worker.wait().await?)?
                .transpose()?
                .into_parts()
                .0,
        );
        break;
    }
    assertion.context("Repository publishes no supported digest")
}
